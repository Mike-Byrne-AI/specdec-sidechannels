#!/usr/bin/env python3
"""Extract a compact deterministic godfile summarizing Trellis state.

The godfile is a short generated map of trellis-docs/trellis-findings.md,
trellis-docs/trellis-decisions.md, trellis-docs/trellis-runs.md, and active top-level task packs. It is not a replacement for
those sources. If it disagrees with them, the sources win and the godfile is
stale.

Output: .claude/GODFILE.md (derived; ignored by default).

Usage:
    python tools/trellis_extract_godfile.py
    python tools/trellis_extract_godfile.py --check
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path

_PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(_PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(_PROJECT_ROOT))

from tools.trellis_paths import (  # noqa: E402
    TrellisPathError,
    active_task_packs,
    decisions_path,
    findings_path,
    get_project_root,
    godfile_sources,
    rel_posix,
    runs_path,
)

FINDING_HEADER_RE = re.compile(r"^#{2,3}\s+(F\d+)\b\s*(?:[—-]\s*)?(.*)$")
DECISION_HEADER_RE = re.compile(
    r"^##\s+(D-\d+)\s*[—-]\s*(.+?)\s+\[(verified|probable|imagined)\]\s*$"
)
RUN_ROW_RE = re.compile(r"^\|\s*(run_\d+)\s*\|")


def read_lines(path: Path) -> list[str]:
    if not path.exists():
        return []
    return path.read_text(encoding="utf-8").splitlines()


def extract_findings(findings_path: Path) -> list[tuple[str, str]]:
    """Return (finding_id, one_line_summary) from trellis-docs/trellis-findings.md."""
    lines = read_lines(findings_path)
    out: list[tuple[str, str]] = []
    for i, line in enumerate(lines):
        m = FINDING_HEADER_RE.match(line)
        if not m:
            continue
        finding_id = m.group(1)
        summary = (m.group(2) or "").strip()
        if not summary:
            for candidate in lines[i + 1 : min(i + 10, len(lines))]:
                stripped = candidate.strip()
                if stripped and not stripped.startswith("#"):
                    summary = stripped
                    break
        if len(summary) > 100:
            summary = summary[:97] + "..."
        out.append((finding_id, summary))

    seen: set[str] = set()
    deduped: list[tuple[str, str]] = []
    for finding_id, summary in out:
        if finding_id not in seen:
            seen.add(finding_id)
            deduped.append((finding_id, summary))
    return deduped


def extract_decisions(decisions_path: Path) -> list[tuple[str, str, str]]:
    """Return (decision_id, title, confidence) from trellis-docs/trellis-decisions.md."""
    out: list[tuple[str, str, str]] = []
    for line in read_lines(decisions_path):
        m = DECISION_HEADER_RE.match(line)
        if m:
            out.append((m.group(1), m.group(2).strip(), m.group(3)))
    return out


def extract_latest_run(runs_path: Path) -> str:
    """Return the last run-row from RUNS.md, or an empty string."""
    last = ""
    for line in read_lines(runs_path):
        if RUN_ROW_RE.match(line):
            last = line
    return last


def build_source_section(project_root: Path) -> list[str]:
    lines = ["Source of truth:"]
    for source in godfile_sources(project_root):
        lines.append(f"- {rel_posix(source, project_root)}")
    if not active_task_packs(project_root):
        lines.append("- task-packs/TP-*.md (none active)")
    return lines


def build_godfile(project_root: Path) -> str:
    findings = extract_findings(findings_path(project_root))
    decisions = extract_decisions(decisions_path(project_root))
    latest_run = extract_latest_run(runs_path(project_root))
    active_packs = active_task_packs(project_root)

    lines: list[str] = [
        "# Godfile - compact project state",
        "",
        "_Generated by `python tools/trellis_extract_godfile.py`. Do not edit by hand._",
        "",
        *build_source_section(project_root),
        "",
        "If the contents below disagree with those files, the source files win.",
        "Regenerate this file after changing any listed source.",
        "",
        "## Latest run",
        latest_run or "_(no runs recorded)_",
        "",
        "## Active task packs",
    ]

    if active_packs:
        for pack in active_packs:
            lines.append(f"- {pack.name}")
    else:
        lines.append("_(none)_")

    lines.extend(["", "## Findings (F-N)"])
    if findings:
        for finding_id, summary in findings:
            lines.append(f"- **{finding_id}**: {summary}")
    else:
        lines.append("_(none recorded)_")

    lines.extend(["", "## Decisions (D-N) with confidence"])
    by_conf: dict[str, list[tuple[str, str]]] = {
        "verified": [],
        "probable": [],
        "imagined": [],
    }
    for decision_id, title, confidence in decisions:
        by_conf.setdefault(confidence, []).append((decision_id, title))

    wrote_confidence = False
    for confidence in ("verified", "probable", "imagined"):
        items = by_conf.get(confidence, [])
        if not items:
            continue
        wrote_confidence = True
        lines.append(f"### [{confidence}]")
        for decision_id, title in items:
            lines.append(f"- **{decision_id}**: {title}")
    if not wrote_confidence:
        lines.append("_(none recorded)_")

    lines.extend(
        [
            "",
            "## How to use this godfile",
            "",
            "- For details on any F-N or D-N, open trellis-docs/trellis-findings.md or trellis-docs/trellis-decisions.md.",
            "- To verify a finding: `python tools/trellis_verify_finding.py F-N --checkpoint <path>`.",
            "- To check freshness: `python tools/trellis_extract_godfile.py --check`.",
            "",
        ]
    )
    return "\n".join(lines)


@dataclass(frozen=True)
class GodfileFreshness:
    status: str
    reason: str = ""

    @property
    def fresh(self) -> bool:
        return self.status == "fresh"


def godfile_freshness(project_root: Path) -> GodfileFreshness:
    """Return content-based freshness for `.claude/GODFILE.md`.

    Status is one of `fresh`, `stale`, `missing`, or `error`. The comparison
    renders the expected godfile content and compares bytes of normalized text;
    it does not depend on filesystem mtimes.
    """
    godfile = project_root / ".claude" / "GODFILE.md"
    if not godfile.exists():
        return GodfileFreshness("missing", "godfile does not exist")
    try:
        actual = godfile.read_text(encoding="utf-8")
        expected = build_godfile(project_root)
    except OSError as exc:
        return GodfileFreshness("error", f"could not read godfile sources: {exc}")
    if actual != expected:
        labels = [rel_posix(path, project_root) for path in godfile_sources(project_root)]
        return GodfileFreshness("stale", f"content differs from rendered Trellis sources: {labels}")
    return GodfileFreshness("fresh", "")


def is_stale(project_root: Path) -> tuple[bool, str]:
    """Backward-compatible stale check returning `(is_stale, reason)`."""
    result = godfile_freshness(project_root)
    return not result.fresh, result.reason


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate or check .claude/GODFILE.md")
    parser.add_argument("--check", action="store_true", help="Check freshness without writing")
    args = parser.parse_args()

    try:
        project_root = get_project_root(Path(__file__).resolve())
    except TrellisPathError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1

    if args.check:
        stale, reason = is_stale(project_root)
        if stale:
            print(f"GODFILE STALE: {reason}")
            print("Run: python tools/trellis_extract_godfile.py")
            return 1
        print("GODFILE is fresh.")
        return 0

    output = build_godfile(project_root)
    out_path = project_root / ".claude" / "GODFILE.md"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(output, encoding="utf-8")
    print(f"Wrote {out_path} ({len(output.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
