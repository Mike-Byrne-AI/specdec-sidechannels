"""Run the full experiment suite (CPU only, ~10-15 min; REWRITES the committed
results/e0*.json + results/summary.json evidence — run deliberately).
--smoke: the fast CI variant (~1-2 min), written to results/smoke/ (gitignored)."""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import e01_verifier_exactness
import e02_crossbucket_audit
import e03_oracle_ceiling
import e04_staleness_decay
import e05_sidecar_recovery
import e06_posterior_mechanism
import e07_hint_rate
from _util import Timer, save_json


def main(smoke: bool = False) -> None:
    if smoke:
        # The CI/smoke variant writes to results/smoke/ (gitignored): the
        # full-mode results/*.json are committed evidence and are only
        # regenerated by a deliberate full `make experiments`.
        from _util import smoke_results
        smoke_results()
    summary = {}
    for mod in (e01_verifier_exactness, e02_crossbucket_audit, e03_oracle_ceiling,
                e04_staleness_decay, e05_sidecar_recovery,
                e06_posterior_mechanism, e07_hint_rate):
        name = mod.__name__
        print(f"\n=== {name} {'(smoke)' if smoke else ''} ===")
        with Timer() as t:
            mod.main(smoke=smoke)
        summary[name] = {"seconds": round(t.seconds, 2)}
    save_json("summary.json", {"smoke": smoke, "runs": summary})


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--smoke", action="store_true")
    main(**vars(ap.parse_args()))
