#!/usr/bin/env python3
"""docs/audits/critic-recovered/gen_readme.py: writes README.md beside it from MANIFEST.json alone (the
public manifest names the withheld files and carries the per-session counts the table needs, so the
generator never opens MANIFEST_WITHHELD.json and regenerates the same bytes in the public clone). The
counts in the README are read from the manifest; the prose, and the few literals in it that describe the
export tool's spec (the residue entries) or the archives' rules, are this file's, and the tool's test holds
the residue wording to the spec. Frozen in the export like the folder.

Run::

    python -I docs/audits/critic-recovered/gen_readme.py [--sibling <archive folder>]...
    python -I docs/audits/critic-recovered/gen_readme.py [--sibling <archive folder>]... --check

A ``--sibling`` names a later archive of critic material (each holds its own MANIFEST.json); its name and
file count go into the "What the archive's rule left behind" section. For a sibling not given on the
command line the count recorded at the last generation is read back from README.md itself, so ``--check``
holds in a clone. ``--check`` compares the regenerated bytes with README.md and writes nothing
(tests/test_critic_recovered.py runs it). The file is written LF, as bytes.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SIBLING_LINE = re.compile(r"^- `([^`]+)` \((\d+) files\)")


def sibling_counts(args: list[str], readme: Path) -> dict[str, int]:
    """Name -> file count: the counts recorded in README.md at the last generation, each overridden by the
    archive's own manifest when its folder is given."""
    out: dict[str, int] = {}
    if readme.exists():
        for line in readme.read_text(encoding="utf-8").splitlines():
            m = SIBLING_LINE.match(line)
            if m and "sideband-critic-scratch-" in m.group(1):
                out[m.group(1)] = int(m.group(2))
    for s in args:
        p = Path(s)
        man = json.loads((p / "MANIFEST.json").read_text(encoding="utf-8"))
        out[p.name] = man["n_files"]
    return out


def render(pub: dict, sib: dict[str, int]) -> str:
    c = pub["counts"]
    withheld_dirs = {w["dir"] for w in pub["withheld"] if "dir" in w}
    withheld_files = [{"path": f["path"], "empty": f["empty"], "session": w["session"]}
                      for w in pub["withheld"] for f in w["files"]]
    withheld_paths = {f["path"] for f in withheld_files}
    rows = [{"path": r["path"], "empty": r["bytes"] == 0, "session": r["session"]} for r in pub["files"]] + withheld_files
    nc = pub["not_copied"][0]
    scrubs = {s["session"]: s["substitutions"] for s in pub["sessions"]}
    s1 = next((k for k in sib if k.endswith("2026-10-17")), "sideband-critic-scratch-2026-10-17")
    omitted = next((k for k in sib if k.endswith("omitted")), "sideband-critic-scratch-2026-10-17-omitted")

    L: list[str] = []
    P = L.append
    P("# The recovered critic folder (2026-10-17)")
    P("")
    P("Lever 3 of the public-cut plan, section 14.2 item 3 (the plan is a withheld file; the public cut's WITHHELD.md")
    P("names it). The image audit's researcher walkthrough (docs/audits/2026-10-15-image-audit/README.md,")
    P("\"Walkthroughs\") named as its second doubt that the reviewer is the same AI and that its reports were")
    P("uncommitted. The reviewer is the sideband critic agent (.claude/agents/sideband-critic.md), dispatched by the")
    P("assistant on the registrations and landings of the harness era; its recompute scripts, their outputs and its")
    P("round reports lived only in the per-session scratch under the box's Temp folder. On 2026-10-16 a selection of")
    P("them was copied, with a sha256 manifest, to a dated archive outside Temp and outside the repository")
    P(f"(`C:\\Users\\<user>\\Desktop\\Research\\{pub['archive']['name']}`, {c['archive']} files, copied")
    P(f"{pub['archive']['copied'][:19]}Z; its manifest's sha256 is in MANIFEST.json). The archive's rule, recovered from the")
    P(f"archive itself on {pub['recovered_on']} (it rebuilds the archive exactly): {pub['archive']['rule'].split(' (recovered', 1)[0]}.")
    P(f"This folder is that archive, copied by `recover.py` beside it on {pub['recovered_on']}: {c['copied']} files under")
    P(f"{len(pub['sessions'])} session folders, one file listed and not copied, two manifests pinning every byte. What the rule")
    P("left behind is named below. Everything here is labelled RECOVERED: it is a selection of the reviewer's scratch as")
    P("it was left, not a registered instrument and not a result.")
    P("")
    P("## What it is, and what it is not")
    P("")
    P("- The scripts are what the reviewer ran to recompute labels and numbers from the committed state files and")
    P("  payloads at the time; the `.json` files are their outputs; the `.txt` and `.md` files are its round reports,")
    P("  the diffs and record excerpts it read, and its scratch notes. A script's paths point at the session scratchpad")
    P("  of its day (scrubbed, see below), so no script runs as copied; none is re-run by any test, and none is an")
    P("  instrument whose bytes a payload attests.")
    P("- What the folder establishes is narrower than independence: that the recompute rounds the record's OUTCOME")
    P("  blocks and memory rows describe existed, in part, and what those rounds computed and reported. The reviewer")
    P("  is an agent of the same model family as the assistant that wrote the registrations: the agent file")
    P("  .claude/agents/sideband-critic.md carries `model: opus` in every version since c20dce4 (2026-10-01, before")
    P("  the first file here), the later versions ab12cbd and c2b45ff included. The outside half of the doubt, a rerun")
    P("  of the committed audit scripts by a non-Anthropic model or a human colleague, stays the operator's action")
    P("  (section 14.2's closing paragraph).")
    P("- A report's claims are the reviewer's at its date. Later rounds and landings answered or superseded some of")
    P("  them; the record's dated text, not the report, is authoritative. Where a report quotes a number, the")
    P("  committed payload it recomputed from is the source.")
    P("- The folder covers the harness era only (2026-10-01 to 2026-10-16). The September rounds, F-24's among them,")
    P("  are not here: the scratch root of the repository's earlier path holds nothing (section 14.2 item 3 records")
    P("  the search).")
    P("")
    P("## Layout, scrub, lanes, manifests")
    P("")
    P(f"- Layout: `{pub['layout']}`.")
    P(f"- Scrub: {pub['scrub']}. {c['scrubbed_files']} files carry {c['substitutions']} substitutions in all")
    P(f"  ({c['scrubbed_files_exported']} files and {c['substitutions_exported']} in the exported rows); the archive digest")
    P("  (`sha256_source`) and the committed digest (`sha256`) of every row record the change, and a row with no")
    P("  substitution has the two equal. A reader who knows the name can reproduce an archive digest from the")
    P("  committed bytes; the name is public in the record's author block and in the own-checkout paths the export")
    P("  keeps, so the digest hides nothing the tree does not already show. The scrubbed form of the scratchpad root")
    P("  reads `C:\\Users\\<user>\\AppData\\Local\\Temp\\claude\\c--Users-<user>-Desktop-Research-sideband\\<session>\\scratchpad\\`.")
    P("  Nothing else in any file changed; line endings are kept (the manifests record each file's form). The bare")
    P(f"  name remains in {c['bare_name_files_left']} file(s), {c['bare_name_occurrences_left']} occurrence(s): a copied")
    P("  test fixture quoting the public author name, in a withheld file.")
    P(f"- Lanes: {pub['lane_rule']}. A file past every window of its session would have been an error, not a guess.")
    P("  In the table, each window shows its closing commit first, the lane's other commits after it, and the number")
    P("  of files it holds; a window with 0 files is a lane whose rounds the archive's rule did not catch.")
    P("- Manifests: MANIFEST.json holds the rows the public cut exports and lists the withheld sessions and files by")
    P("  name and count, with no digest of a withheld file; MANIFEST_WITHHELD.json holds the withheld rows with their")
    P("  digests and is withheld with them. Each row: committed path, archive path, session, lane, commits, archive")
    P("  mtime, both sizes, both digests, substitution count, line-ending form, export status. `recover.py` writes")
    P("  both; `gen_readme.py` writes this file from MANIFEST.json alone (it names the withheld files and carries the")
    P("  per-session counts), so the public clone regenerates the same bytes.")
    P("")
    P("## Sessions and lanes")
    P("")
    P("| Folder | Session | Files | Scrubs | Lane windows (closing commit first; files before its time take the window) |")
    P("|---|---|---|---|---|")
    for s in pub["sessions"]:
        wins = "; ".join(f"{w['lane']} ({w['commits']}) [{w['n_files']}]" for w in s["windows"])
        tag = " (withheld from the public cut)" if s["dir"] in withheld_dirs else ""
        P(f"| `{s['dir']}`{tag} | `{s['session'][:8]}` | {s['n_files']} | {scrubs.get(s['session'], 0)} | {wins} |")
    P("")
    P("## What the archive's rule left behind")
    P("")
    P("The rule took only the top-level files of four suffixes inside critic-named folders. Still in Temp on")
    P("2026-10-17, and copied that day to a second archive by a wider rule (every file under a critic-named folder at")
    P("any depth, except copied trees and results copies, and every file whose name starts with critic outside such a")
    P("folder), were: the nested round folders of three sessions (the harness initialisation's rounds two and three,")
    P("EVID-1's rounds five to seven, the reader-and-lens landings' probe outputs), the `.log` captures beside the")
    P("archived scripts, the dispatch briefs the assistant wrote for some rounds, the registration report of the")
    P("reader-and-lens re-test (`critic_design_report.txt`, the window the table shows with 0 files) and the five")
    P("critic reads of the public-cut decision batch's lane 2 (`lane2/reviews/critic_read1.md` to `critic_read5.md`).")
    P("The S1 reader re-test lane's rounds (2026-10-16/17) postdate the first archive and sit in a third copy. Landing")
    P("either as a dated addendum to this folder is a separate call. The copies, beside the first archive:")
    P("")
    P(f"- `{s1}` ({sib.get(s1, 0)} files): the S1 reader re-test lane's critic scratch (session 2722c7ea).")
    P(f"- `{omitted}` ({sib.get(omitted, 0)} files): what the first archive's rule left behind, by the wider rule.")
    P("")
    P("Lanes of the era whose rounds appear in neither archive: the free-bigram twin's landing rounds and the fourth")
    P("session's three rounds over the derived ledgers (2026-10-01), the noise-floor registration (906edfd) and the")
    P("horizon-read landing (b71e9ca) of 2026-10-04, the OQ-20 landing's five critic rounds (2026-10-10), the docs")
    P("lanes of 2026-10-11 and 2026-10-12 (the record lines, the public-cut plan and the root README's four rounds")
    P("among them), the nineteenth session's rounds, run from the lockstep checkout and so under that checkout's Temp")
    P("slug, and the image audit's lanes B and C, which left no critic-named folder (lane C's session left two")
    P("reviewer scripts, in the second archive). ESPALIER_MEMORY.md's session rows describe each.")
    P("")
    P("## Withheld from the public cut")
    P("")
    P(f"{c['withheld']} of the {c['copied']} copied files are withheld from the public cut and stay in the private tree:")
    P("")
    for w in pub["withheld"]:
        if "dir" in w:
            P(f"- `{w['dir']}/` ({w['n_files']} file{'s' if w['n_files'] != 1 else ''}): {w['reason']}.")
        else:
            P(f"- `{w['path']}`: {w['reason']}.")
    P("- `MANIFEST_WITHHELD.json`: their rows and digests.")
    P("")
    P("The reasons above are the export tool's own (its spec holds the same keys and wording, pinned to this manifest")
    P(f"by the tool's test). The public reader sees the other {c['exported']} files byte for byte, the science lanes'")
    P("rounds among them, fourteen of them with a residue entry in the tool's spec for a mention a frozen file cannot")
    P("mark: twelve quote the record's own pointer to a withheld idea file, one is the R1 landing diff the critic")
    P("read (its hunk of the idea file is the dated status line the record also holds in OPEN_QUESTIONS.md and")
    P("README.md), one holds a git status line naming the withheld test. WITHHELD.md lists them.")
    P("")
    P("## Listed and not copied")
    P("")
    P(f"- `{nc['source_path']}` (would have been `{nc['path']}`; {nc['bytes_source']:,} bytes, sha256 `{nc['sha256_source']}`):")
    P(f"  {nc['why']}.")
    P("")
    P("## Where the words are")
    P("")
    P("The reports and record excerpts, by folder (the scripts and outputs sit beside them; MANIFEST.json is the full")
    P("index; a file marked withheld is not in the public cut):")
    P("")
    def wordish(r: dict) -> bool:
        name = r["path"].rsplit("/", 1)[1]
        return r["path"].endswith(".md") or (r["path"].endswith(".txt") and any(
            k in name for k in ("report", "outcome", "block_now", "status", "added", "removed", "diff_", "mine", "sweep", "dry", "cl_", "plan")))
    for s in pub["sessions"]:
        rs = sorted((r for r in rows if r["session"] == s["session"] and wordish(r)), key=lambda r: r["path"])
        if not rs:
            continue
        items = []
        for r in rs:
            rel = r["path"][len(s["dir"]) + 1:]
            name = f"[{rel}]({r['path']})" if r["path"].endswith(".md") and r["path"] not in withheld_paths else f"`{rel}`"
            name += " (withheld)" if r["path"] in withheld_paths else ""
            name += " (empty)" if r["empty"] else ""
            items.append(name)
        P(f"- `{s['dir']}/`: " + ", ".join(items) + ".")
    P("")
    P("## Holding the folder to its manifests")
    P("")
    P("- `tests/test_critic_recovered.py`: every row's file present with its digest and size on disk and in the index")
    P("  (`git hash-object --no-filters`), git's `text` attribute unset on every file (the glob line in .gitattributes;")
    P("  a checkout's autocrlf never rewrites these bytes), no home-path user segment other than the token and the")
    P("  fixture names of the copied tests, the lane of every row re-derived from the manifest's own windows and, where")
    P("  the commits resolve, the windows' times checked against git, the counts consistent across the two manifests,")
    P("  and this README regenerated byte for byte. It reads whichever manifests are present, so it holds in the public")
    P("  clone too.")
    P("- `python -I docs/audits/critic-recovered/recover.py --source <the archive> --date " + pub["recovered_on"] + " --check` rebuilds")
    P("  the folder in memory from the archive and reports any byte that differs and any file the build would not write")
    P("  (0 and none at the landing).")
    P("- The folder's session folders are left out of ruff (pyproject `extend-exclude`), and all of it out of the")
    P("  evidence-bytes citer scans (tests/test_evidence_bytes.py and tools/evidence_pins.py, RECOVERED_PREFIXES): its")
    P("  files quote digests of results files and instruments in whichever form the reviewer hashed, and the manifests")
    P("  quote the folder's own digests, none of which is a citation the record makes. In the public cut the folder is")
    P("  frozen (emitted byte for byte) and outside the tone sweep, like the logs.")
    P("- [docs/REPORT.md](../../REPORT.md), FINDINGS.md and docs/WHY_THIS_DIES.md are the record; the copies of them here (the")
    P("  landing-text kit's session read them as they stood on 2026-10-03) are the reviewer's inputs of that day.")
    return "\n".join(L) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    ap.add_argument("--sibling", action="append", default=[], help="a later archive folder with its MANIFEST.json")
    ap.add_argument("--check", action="store_true", help="compare the regenerated README with the file; write nothing")
    a = ap.parse_args(argv)
    pub = json.loads((HERE / "MANIFEST.json").read_text(encoding="utf-8"))
    readme = HERE / "README.md"
    text = render(pub, sibling_counts(a.sibling, readme)).encode("utf-8")
    if a.check:
        same = readme.exists() and readme.read_bytes() == text
        print("README.md " + ("matches" if same else "differs from") + " the manifests")
        return 0 if same else 1
    readme.write_bytes(text)
    print(f"wrote README.md ({len(text)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
